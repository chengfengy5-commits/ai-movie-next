"""Persistence and provider ports for storyboard generation."""

from __future__ import annotations

from collections.abc import AsyncIterator, Callable
from typing import Protocol

from haoai_backend.shared.identity import TrustedActor

from .domain import StoryboardPrompt, StoryboardRuntimeCall, StoryboardRuntimeResult, StoryboardServerModel


class StoryboardGenerationRuntime(Protocol):
    """Configured server-side runtime; implementations own provider defaults."""

    async def generate(self, call: StoryboardRuntimeCall) -> StoryboardRuntimeResult: ...

    def stream(self, call: StoryboardRuntimeCall) -> AsyncIterator[str]: ...



class StoryboardGenerationUnitOfWork(Protocol):
    def resolve_model(self, actor: TrustedActor, model_id: str) -> StoryboardServerModel: ...
    def resolve_prompt(self, actor: TrustedActor, prompt_id: str | None) -> StoryboardPrompt: ...
    def require_series_access(self, actor: TrustedActor, series_id: str) -> None: ...
    def validate_task(self, actor: TrustedActor, task_id: str | None) -> None: ...
    def write_task_result(self, actor: TrustedActor, task_id: str, *, status: str, result: str | None) -> bool: ...
    def create_chapter(self, actor: TrustedActor, *, series_id: str, title: str, order: int, frames: Sequence[Mapping[str, object]]) -> tuple[str, list[dict[str, object]]]: ...
    def commit(self) -> None: ...
    def rollback(self) -> None: ...
    def close(self) -> None: ...


StoryboardGenerationUnitOfWorkFactory = Callable[[], StoryboardGenerationUnitOfWork]
